/**
 * List of all available Day.js units
 * @link https://day.js.org/docs/en/display/difference#list-of-all-available-units
 */
export enum DayjsUnits {
  /**
   * Day of Week (Sunday as 0, Saturday as 6)
   */
  day = 'd',
  /**
   * Week of Year
   */
  week = 'w',
  /**
   * Quarter
   */
  quarter = 'Q',
  /**
   * Month (January as 0, December as 11)
   */
  month = 'M',
  /**
   * Year
   */
  year = 'y',
  /**
   * Hour
   */
  hour = 'h',
  /**
   * Minute
   */
  minute = 'm',
  /**
   * Second
   */
  second = 's',
  /**
   * Millisecond
   */
  millisecond = 'ms',
}
